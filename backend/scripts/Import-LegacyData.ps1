param(
    [string]$Server = 'localhost',
    [string]$SourceDatabase = 'VNC_HRMS_Iteration1',
    [string]$DatabasePrefix = 'VNC'
)
# Offline, one-time migration. Stop writes in the legacy application before running.
# Source tables are read only. Destination IAM/HR must be empty (use Initialize-Local -SkipBootstrap).
$ErrorActionPreference = 'Stop'
function Quote-Identifier([string]$value) { '[' + $value.Replace(']',']]') + ']' }
$source = Quote-Identifier $SourceDatabase
$iam = Quote-Identifier "${DatabasePrefix}_IAM_DB"
$hr = Quote-Identifier "${DatabasePrefix}_HR_DB"
if ($SourceDatabase -in @("${DatabasePrefix}_IAM_DB", "${DatabasePrefix}_HR_DB")) { throw 'Source must differ from destination.' }
$connectionBuilder = New-Object System.Data.SqlClient.SqlConnectionStringBuilder
$connectionBuilder['Data Source'] = $Server; $connectionBuilder['Initial Catalog'] = 'master'
$connectionBuilder['Integrated Security'] = $true; $connectionBuilder['Encrypt'] = $true; $connectionBuilder['TrustServerCertificate'] = $true
$connection = New-Object System.Data.SqlClient.SqlConnection $connectionBuilder.ConnectionString
$tables = @(
    @($iam,'iam','users','users'),
    @($iam,'iam','credentials','auth'),
    @($hr,'hr','positions','organization'),
    @($hr,'hr','departments','organization'),
    @($hr,'hr','staff','employees'),
    @($hr,'hr','contracts','employees'),
    @($hr,'hr','degrees','employees')
)
$transaction = $null
try {
    $connection.Open()
    $transaction = $connection.BeginTransaction([System.Data.IsolationLevel]::Serializable)
    foreach ($entry in $tables) {
        $destination,$schema,$table,$oldSchema = $entry
        $command = $connection.CreateCommand(); $command.Transaction = $transaction; $command.CommandTimeout = 120
        $targetTable = "$destination.$schema.$table"
        $sourceTable = "$source.$oldSchema.$table"
        # Require matching column names; rowversions are regenerated by SQL Server.
        # Department manager is restored after staff because of the circular HR relationship.
        $excludeManager = if ($table -eq 'departments') { "AND target.name <> 'manager_id'" } else { '' }
        $command.CommandText = @"
SET XACT_ABORT ON;
IF EXISTS (SELECT 1 FROM $targetTable WITH (UPDLOCK,HOLDLOCK)) THROW 51000, 'Destination tables must be empty.', 1;
DECLARE @columns nvarchar(max);
SELECT @columns = STRING_AGG(CONVERT(nvarchar(max),QUOTENAME(target.name)), ',') WITHIN GROUP (ORDER BY target.column_id)
FROM $destination.sys.columns target
JOIN $destination.sys.tables tt ON tt.object_id = target.object_id
JOIN $destination.sys.schemas ts ON ts.schema_id = tt.schema_id
JOIN $source.sys.tables st ON st.name = tt.name
JOIN $source.sys.schemas ss ON ss.schema_id = st.schema_id AND ss.name = '$oldSchema'
JOIN $source.sys.columns old ON old.object_id = st.object_id AND old.name = target.name
WHERE ts.name = '$schema' AND tt.name = '$table' AND target.system_type_id <> 189 AND target.is_computed = 0 $excludeManager;
IF @columns IS NULL THROW 51001, 'Source or destination schema is missing.', 1;
DECLARE @sql nvarchar(max) = N'INSERT INTO $targetTable (' + @columns + ') SELECT ' + @columns + ' FROM $sourceTable;';
EXEC sys.sp_executesql @sql;
IF (SELECT COUNT_BIG(*) FROM $targetTable) <> (SELECT COUNT_BIG(*) FROM $sourceTable) THROW 51002, 'Row count mismatch.', 1;
"@
        [void]$command.ExecuteNonQuery()
        Write-Output "Copied $oldSchema.$table -> $schema.$table (transaction pending)."
    }
    $command = $connection.CreateCommand(); $command.Transaction = $transaction; $command.CommandTimeout = 120
    $command.CommandText = @"
UPDATE target SET manager_id = old.manager_id
FROM $hr.hr.departments target JOIN $source.organization.departments old ON old.department_id = target.department_id;
IF EXISTS (SELECT 1 FROM $iam.iam.users u LEFT JOIN $hr.hr.staff s ON u.employee_id = s.staff_id WHERE u.employee_id IS NOT NULL AND s.staff_id IS NULL)
    THROW 51003, 'Legacy account references a missing employee.', 1;
IF EXISTS (SELECT 1 FROM $hr.hr.staff s JOIN $iam.iam.users u ON u.employee_id=s.staff_id WHERE s.user_id IS NOT NULL AND s.user_id<>u.user_id)
    THROW 51004, 'Conflicting employee-account links.', 1;
UPDATE s SET user_id=u.user_id FROM $hr.hr.staff s JOIN $iam.iam.users u ON u.employee_id=s.staff_id;
UPDATE $iam.iam.users SET role='hr_manager', security_version=security_version+1, updated_at=SYSUTCDATETIME() WHERE role='hr';
"@
    [void]$command.ExecuteNonQuery()
    $transaction.Commit()
    Write-Output 'Import committed. IDs, password hashes and business rows preserved. Sessions/OTP were not copied; users must log in again. Source database unchanged.'
} catch {
    if ($transaction) { try { $transaction.Rollback() } catch { } }
    throw
} finally { if ($transaction) { $transaction.Dispose() }; $connection.Dispose() }
